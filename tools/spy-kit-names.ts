// Writes packages/engine/src/spy-kit-names.ts: the names of nonlegendary creature cards (Spy Kit, CR 612.7) that some
// card's rules text mentions ("a token named Llanowar Elves", "creatures named Relentless Rats"). The game data holds only
// the cards in the game, so a name that reaches the game only through text is looked up here; the names of the cards in
// the game are worked out from their definitions (all-names.ts).
//
//   npx tsx tools/spy-kit-names.ts           (needs data/generated/cards.json)

import { readFileSync, writeFileSync } from "node:fs";
import { spyKitTextNames, type CardDef } from "../packages/engine/src";

const cards: CardDef[] = JSON.parse(readFileSync(new URL("../data/generated/cards.json", import.meta.url), "utf8"));
const names = spyKitTextNames(cards);
const body = names.map((n) => `  ${JSON.stringify(n)},`).join("\n");
writeFileSync(
  new URL("../packages/engine/src/spy-kit-names.ts", import.meta.url),
  `// Generated by tools/spy-kit-names.ts from the card data: the names of nonlegendary creature cards (any face, CR 612.7)\n// that appear in some card's rules text. Don't edit by hand.\nexport const SPY_KIT_TEXT_NAMES: readonly string[] = [\n${body}\n];\n`,
);
console.log(`${names.length} names`);
